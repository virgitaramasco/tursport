  var currentLang = 'it';

  function applyLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    try { localStorage.setItem('tursport_lang', lang); } catch (e) {}
    document.documentElement.setAttribute('lang', lang);

    // Aggiorna bottoni lingua
    document.querySelectorAll('.lang-btn').forEach(function(btn){
      if(btn.getAttribute('data-lang') === lang){
        btn.classList.add('is-active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('is-active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // Aggiorna testi data-i18n
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      if(translations[lang][key]){
        el.innerHTML = translations[lang][key];
      }
    });

    // Aggiorna placeholder data-i18n-ph
    document.querySelectorAll('[data-i18n-ph]').forEach(function(el){
      var key = el.getAttribute('data-i18n-ph');
      if(translations[lang][key]){
        el.setAttribute('placeholder', translations[lang][key]);
      }
    });

    // Aggiorna select motivo
    var sel = document.getElementById('c-motivo');
    if(sel){
      var optKeys = [
        'form_reason_select', 'form_reason_opt1', 'form_reason_opt2',
        'form_reason_opt3', 'form_reason_opt4', 'form_reason_opt5',
        'form_reason_opt6', 'form_reason_opt7'
      ];
      for(var i=0; i<sel.options.length && i<optKeys.length; i++){
        sel.options[i].textContent = translations[lang][optKeys[i]];
      }
    }

    // Aggiorna Titolo e Descrizione documento
    if(translations[lang].page_title) document.title = translations[lang].page_title;
    var metaDesc = document.querySelector('meta[name="description"]');
    if(metaDesc && translations[lang].page_desc) metaDesc.setAttribute('content', translations[lang].page_desc);
  }

  // Listener click sui pulsanti lingua
  document.querySelectorAll('.lang-btn').forEach(function(btn){
    btn.addEventListener('click', function(){
      var l = this.getAttribute('data-lang');
      applyLanguage(l);
    });
  });

  // Carica lingua salvata o default
  try {
    var saved = localStorage.getItem('tursport_lang');
    if(saved && translations[saved]){
      applyLanguage(saved);
    }
  } catch(e) {}

